#!/usr/bin/env bash
# The report holds the live peer Service port
set -uo pipefail
fail() { echo "FAIL: $*"; exit 1; }
pass() { echo "PASS: $*"; exit 0; }
http_code() { kubectl -n "$1" exec "$2" -- curl -s -m 5 -o /dev/null -w '%{http_code}' "$3" 2>/dev/null || true; }
evidence() { kubectl -n "$1" get configmap "$2" -o "jsonpath={.data['$3']}" 2>/dev/null; }
expect_equal() { [ -n "$3" ] || fail "$1: could not read the live value"; [ "$2" = "$3" ] || fail "$1: expected '$3' but found '$2'"; }
live="$(kubectl -n kube-system get service hubble-peer -o jsonpath='{.spec.ports[0].port}')"
expect_equal "peer-service-port" "$(evidence starfleet hubble-evidence peer-service-port)" "$live"
pass "peer-service-port matches"
